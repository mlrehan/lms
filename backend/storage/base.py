"""The storage boundary.

One `Protocol`, two implementations: the local filesystem (the default, and
what this deployment uses today) and Cloudflare R2. Everything above this
line -- services, routers -- deals in opaque *keys*, never filesystem paths
or bucket names, so switching `STORAGE_MODE` moves where bytes live without
touching a single caller.

`presigned_url` is the one place the two genuinely differ, and the difference
is deliberate rather than papered over: R2 can hand the client a short-lived
URL and take the download traffic off this server entirely, while a local
file has no such thing and must be streamed back through an authenticated
endpoint. Returning `None` says "no direct URL exists, stream it yourself"
rather than inventing a fake one.
"""

from __future__ import annotations

import re
import uuid
from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import AsyncIterator, Protocol

from backend.core.errors import ValidationError

# A storage key is always generated by us, never supplied by a caller, but
# this is the belt-and-braces check that it stays that way: no traversal, no
# absolute paths, no backslashes, no empty segments.
_SAFE_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9/_.-]{0,511}$")

_SAFE_EXTENSION = re.compile(r"^[a-z0-9]{1,10}$")


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    mime_type: str | None = None


def assert_safe_key(key: str) -> str:
    """Reject anything that could escape the storage root.

    Called on every read *and* write, not just writes: a key that reached the
    database malformed (a migration, a fixture, a bug) would otherwise become
    an arbitrary-file-read the moment someone downloads it.
    """
    if not _SAFE_KEY.match(key):
        raise ValidationError("Malformed storage key.")
    parts = PurePosixPath(key).parts
    if any(p in ("..", ".", "") for p in parts):
        raise ValidationError("Malformed storage key.")
    return key


def build_key(*, prefix: str, filename: str | None) -> str:
    """Generate a storage key for a new upload.

    The client's filename is used *only* to recover an extension, and even
    that is sanitised to a short alphanumeric token. The stored name itself
    is a fresh UUID, so two people uploading `notes.pdf` cannot collide, and
    a filename crafted to traverse or to be executed by a misconfigured web
    server never reaches the filesystem.
    """
    extension = ""
    if filename and "." in filename:
        candidate = filename.rsplit(".", 1)[-1].lower()
        if _SAFE_EXTENSION.match(candidate):
            extension = f".{candidate}"
    return assert_safe_key(f"{prefix.strip('/')}/{uuid.uuid4().hex}{extension}")


class StorageBackend(Protocol):
    """What every backend must provide."""

    async def save(self, key: str, data: bytes, *, content_type: str | None) -> StoredObject: ...

    async def open_stream(self, key: str) -> AsyncIterator[bytes]: ...

    async def delete(self, key: str) -> None: ...

    async def exists(self, key: str) -> bool: ...

    def presigned_url(self, key: str) -> str | None:
        """A direct, time-limited download URL, or `None` if this backend has
        no such concept and the caller must stream the bytes instead."""
        ...
